"""Hand-routed tracks for the C6 energy relay board.

net -> list of paths {"layer": "F"|"B", "w": mm, "pts": [...], "vias": [...]}. Points are board
coordinates (mm, origin top-left, y down, as gen_pcb.PLACE) or pad references ("U1", "17").
Routing style follows the CellKeeper boards: 45-degree corners as planned here (route.py rounds every
bend into an arc when it lays the tracks), splines with s(), 0.2 mm signals, 0.3-0.6 mm power,
0.6/0.3 mm vias, ground poured on both layers. Mains nets stay on the top layer (ZP1 excepted), 1.0 mm (L/N)
and 0.5 mm (divider); relay contacts are copper zones (gen_pcb.RELAY_ZONES).
"""
from __future__ import annotations

from hw.gen_pcb import PLACE  # noqa: E402

ROUTES: dict = {}


def t(net, *pts, w=0.2, layer="F", vias=()):
    ROUTES.setdefault(net, []).append({"layer": layer, "w": w, "pts": list(pts), "vias": list(vias)})


def b(net, *pts, w=0.2, vias=()):
    t(net, *pts, w=w, layer="B", vias=vias)


def s(net, *pts, w=0.2, layer="F", vias=(), start=None, end=None):
    """A smooth spline through the points (hw/spline.py) instead of straight legs with rounded corners.
    start / end: optional directions (dx, dy; y down) it leaves the first and arrives at the last point with.
    A branch must join at one of the points."""
    ROUTES.setdefault(net, []).append({"layer": layer, "w": w, "pts": list(pts), "vias": list(vias),
                                       "spline": True, "start": start, "end": end})


def v(net, *pts):
    ROUTES.setdefault(net, []).append({"layer": "F", "w": 0.2, "pts": [], "vias": list(pts)})


