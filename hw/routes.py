"""Hand-routed tracks for the ESP32-C5 energy relay board (90 x 86 mm).

net -> list of paths {"layer": "F"|"B", "w": mm, "pts": [...], "vias": [...]}. Points are board
coordinates (mm, origin top-left, y down, as gen_pcb.PLACE) or pad references ("U1", "13").
Routing style: 45-degree corners as planned here (route.py rounds every bend into an arc), splines
with s(), 0.2 mm signals, 0.3-0.6 mm power, 0.6/0.3 mm vias, ground poured on both layers, solid
3V3 heat spreader pour on U3's SOT-223 tab, zero tracks under U1 on either layer. Mains nets stay
on the top layer (ZP1 excepted), 1.0 mm (L/N) and 0.5 mm (divider); relay contacts are copper zones.
"""
from __future__ import annotations

